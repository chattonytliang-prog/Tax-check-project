export function trialWarningIndicator(row: number, inputs: readonly string[]) {
  const rule = warningTrials[row]
  if (!rule) return '此指标暂不支持试算。'
  if (inputs.length !== rule.labels.length || inputs.some((value) => value.trim() === '' || !Number.isFinite(Number(value)))) {
    return '请填齐全部取数项。空白不按零处理。'
  }
  const values = inputs.map(Number)
  if (!rule.valid(values)) return '不满足试算前提，请核对基数或金额口径。'
  return rule.matches(values) ? '触发内部预警，需复核。' : '未触发此项预警。'
}
