type WarningTrial = { labels: readonly string[]; valid: (values: number[]) => boolean; matches: (values: number[]) => boolean }

function yearOverYear(metric: string): WarningTrial {
  return {
    labels: [`本期${metric}（元）`, `上年同期${metric}（元）`],
    valid: ([, previous]) => previous > 0,
    matches: ([current, previous]) => Math.abs(current - previous) > previous / 2,
  }
}

